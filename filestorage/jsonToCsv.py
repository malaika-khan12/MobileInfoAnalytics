def run_conversion(args: argparse.Namespace) -> dict[str, Any]:
    input_dir = args.input_dir.resolve()
    output_dir = args.output_dir.resolve()
    canonical_source = canonical_site(args.canonical_source)
    currency = args.currency.strip().upper()
    if not re.fullmatch(r"[A-Z]{3}", currency):
        raise ValueError("--currency must be a three-letter ISO-style code such as PKR or USD")

    selected_sites = {canonical_site(x) for x in args.site} if args.site else None
    paths = discover_paths(input_dir, selected_sites)
    generated_at = datetime.now(timezone.utc).isoformat(timespec="seconds")

    records: list[PhoneRecord] = []
    rejects: list[RejectRecord] = []
    discovered_by_source: dict[str, int] = {}
    success_by_source: dict[str, int] = {}
    failure_by_source: dict[str, int] = {}

    for index, path in enumerate(paths, start=1):
        site = canonical_site(path.parent.name)
        relative = path.relative_to(input_dir).as_posix()
        discovered_by_source[site] = discovered_by_source.get(site, 0) + 1
        try:
            record = load_phone_json(path, input_dir)
            records.append(record)
            success_by_source[site] = success_by_source.get(site, 0) + 1
        except ConversionError as exc:
            failure_by_source[site] = failure_by_source.get(site, 0) + 1
            rejects.append(RejectRecord(site, relative, "", exc.code, str(exc)))
            LOG.error("%s: %s", relative, exc)
            if args.strict:
                raise
        if index % 1000 == 0:
            LOG.info("Validated %d/%d JSON files", index, len(paths))

    assign_identity_slugs(records)

    # Duplicate source URLs are invalid because listings.market_listings.source_url is UNIQUE
    # and staging lineage must remain one-record-per-source-page.
    seen_source_urls: dict[tuple[str, str], PhoneRecord] = {}
    deduped: list[PhoneRecord] = []
    for record in sorted(records, key=lambda r: (r.source_domain, r.source_url, r.source_file)):
        marker = (record.source_domain, record.source_url)
        if marker in seen_source_urls:
            first = seen_source_urls[marker]
            failure_by_source[record.source_domain] = failure_by_source.get(record.source_domain, 0) + 1
            success_by_source[record.source_domain] = max(0, success_by_source.get(record.source_domain, 0) - 1)
            rejects.append(RejectRecord(
                record.source_domain,
                record.source_file,
                record.source_url,
                "DUPLICATE_URL",
                f"Duplicate URL; first accepted from {first.source_file}",
                record.payload,
            ))
            if args.strict:
                raise ConversionError("DUPLICATE_URL", rejects[-1].message)
            continue
        seen_source_urls[marker] = record
        deduped.append(record)
    records = deduped

    assign_listings(records, canonical_source)

    # One canonical specs row per product.  If duplicate canonical records exist,
    # retain the most complete one, then the lexicographically first source file.
    canonical_candidates: dict[int, list[PhoneRecord]] = {}
    for record in records:
        if record.source_domain == canonical_source:
            canonical_candidates.setdefault(record.product_id, []).append(record)
    canonical_record_by_product: dict[int, PhoneRecord] = {}
    for product_id, candidates in canonical_candidates.items():
        canonical_record_by_product[product_id] = sorted(
            candidates,
            key=lambda r: (-r.completeness_pct, r.source_file),
        )[0]

    # Deterministic source run IDs are shared by listings/rejects.
    sources = sorted(set(discovered_by_source) | {r.source_domain for r in records})
    run_id_by_source = {source: stable_bigint("scrape_run", source) for source in sources}

    temp_root = output_dir.with_name(f".{output_dir.name}.build.{os.getpid()}")
    if temp_root.exists():
        shutil.rmtree(temp_root)

    counts: dict[str, int] = {table: 0 for table in TABLE_FIELDS}
    manifest_record_count = 0
    try:
        with CsvTree(temp_root) as out:
            # metadata.scrape_runs
            for source in sources:
                processed = discovered_by_source.get(source, 0)
                failed = failure_by_source.get(source, 0)
                succeeded = success_by_source.get(source, 0)
                out.write("metadata.scrape_runs", {
                    "run_id": run_id_by_source[source],
                    "source_domain": source,
                    "started_at": generated_at,
                    "finished_at": generated_at,
                    "records_processed": processed,
                    "records_succeeded": succeeded,
                    "records_failed": failed,
                    "run_status": "completed" if failed == 0 else "completed_with_errors",
                })
                counts["metadata.scrape_runs"] += 1

            # Catalog companies.
            company_rows: dict[int, dict[str, Any]] = {}
            for record in records:
                company_rows.setdefault(record.company_id, {
                    "company_id": record.company_id,
                    "company_name": record.company_name,
                    "company_slug": record.company_slug,
                    "created_at": generated_at,
                })
            for row in sorted(company_rows.values(), key=lambda r: str(r["company_slug"])):
                out.write("catalog.companies", row)
                counts["catalog.companies"] += 1

            # Catalog products.
            product_groups: dict[int, list[PhoneRecord]] = {}
            for record in records:
                product_groups.setdefault(record.product_id, []).append(record)
            for product_id, group in sorted(product_groups.items(), key=lambda item: item[1][0].product_slug):
                representative = sorted(
                    group,
                    key=lambda r: (r.source_domain != canonical_source, -r.completeness_pct, r.source_file),
                )[0]
                sources_for_product = sorted({r.source_domain for r in group})
                created_by = canonical_source if canonical_source in sources_for_product else sources_for_product[0]
                out.write("catalog.products", {
                    "product_id": product_id,
                    "company_id": representative.company_id,
                    "mobile_name": representative.mobile_name,
                    "product_slug": representative.product_slug,
                    "created_by_source": created_by,
                    "created_at": generated_at,
                    "updated_at": generated_at,
                })
                counts["catalog.products"] += 1

            # product_aliases: emit only genuine alternative cleaned identities that map
            # to the same product.  With template_v2 this is normally empty, which is
            # preferable to manufacturing aliases that were not observed.
            alias_rows: dict[str, dict[str, Any]] = {}
            for product_id, group in product_groups.items():
                canonical = sorted(group, key=lambda r: (r.source_domain != canonical_source, r.source_file))[0]
                canonical_full = display_name(canonical.company_name, canonical.mobile_name)
                canonical_alias_slug = slugify(canonical_full)
                for record in group:
                    alias_name = display_name(record.company_name, record.mobile_name)
                    alias_slug = slugify(alias_name)
                    if alias_slug == canonical_alias_slug:
                        continue
                    alias_rows.setdefault(alias_slug, {
                        "alias_id": stable_bigint("alias", alias_slug),
                        "product_id": product_id,
                        "alias_name": alias_name,
                        "alias_slug": alias_slug,
                        "source_domain": record.source_domain,
                        "created_at": generated_at,
                    })
            for row in sorted(alias_rows.values(), key=lambda r: str(r["alias_slug"])):
                out.write("catalog.product_aliases", row)
                counts["catalog.product_aliases"] += 1

            # Canonical GSMArena specification tables.
            for product_id, record in sorted(canonical_record_by_product.items(), key=lambda item: item[1].product_slug):
                for table, row in canonical_rows(record, generated_at, canonical_source).items():
                    out.write(table, row)
                    counts[table] += 1

            # Marketplace listing tables and structured prices.
            for record in sorted(
                (r for r in records if r.source_domain != canonical_source),
                key=lambda r: (r.source_domain, r.product_slug, r.instance_number or 0, r.source_url),
            ):
                rows_by_table = listing_rows(
                    record,
                    generated_at,
                    run_id_by_source[record.source_domain],
                    currency,
                )
                for table, rows in rows_by_table.items():
                    out.write_many(table, rows)
                    counts[table] += len(rows)

            # Staging, data quality and manifest inventory for every accepted JSON.
            for record in sorted(records, key=lambda r: (r.source_domain, r.source_file)):
                staging_id = stable_bigint("staging", f"{record.source_domain}\0{record.source_file}")
                out.write("staging.raw_json_records", {
                    "staging_id": staging_id,
                    "record_key": record.record_key,
                    "source_domain": record.source_domain,
                    "source_file": record.source_file,
                    "source_url": record.source_url,
                    "payload": compact_json(record.payload),
                    "ingested_at": generated_at,
                    "processed_at": generated_at,
                    "status": "processed",
                })
                counts["staging.raw_json_records"] += 1

                quality_target = (
                    f"product:{record.product_id}"
                    if record.source_domain == canonical_source
                    else f"listing:{record.listing_id}"
                )
                out.write("metadata.data_quality", {
                    "score_id": stable_bigint("quality", f"{record.source_domain}\0{quality_target}\0{record.source_file}"),
                    "product_id": record.product_id,
                    "listing_id": "" if record.source_domain == canonical_source else record.listing_id,
                    "source_domain": record.source_domain,
                    "completeness_pct": f"{record.completeness_pct:.2f}",
                    "fields_populated": record.completeness_populated,
                    "fields_total": record.completeness_total,
                    "scored_at": generated_at,
                })
                counts["metadata.data_quality"] += 1

                out.write("_manifest.records", {
                    "record_key": record.record_key,
                    "source_domain": record.source_domain,
                    "source_file": record.source_file,
                    "source_url": record.source_url,
                    "company_name": record.company_name,
                    "mobile_name": record.mobile_name,
                    "company_slug": record.company_slug,
                    "product_slug": record.product_slug,
                    "product_id": record.product_id,
                    "listing_id": record.listing_id or "",
                    "is_canonical": "true" if record.source_domain == canonical_source else "false",
                    "completeness_pct": f"{record.completeness_pct:.2f}",
                    "file_sha256": record.file_sha256,
                })
                manifest_record_count += 1

            # Rejects are represented in both metadata.etl_rejects and manifest errors.
            for reject in rejects:
                run_id = run_id_by_source.get(reject.source_domain)
                reject_key = f"{reject.source_domain}\0{reject.source_file}\0{reject.code}"
                out.write("metadata.etl_rejects", {
                    "reject_id": stable_bigint("reject", reject_key),
                    "scrape_run_id": run_id or "",
                    "source_domain": reject.source_domain,
                    "source_url": reject.source_url,
                    "source_file": reject.source_file,
                    "reject_reason": reject.code,
                    "reject_detail": reject.message,
                    "raw_payload": compact_json(reject.payload) if reject.payload is not None else "",
                    "rejected_at": generated_at,
                    "resolved_at": "",
                    "resolution_detail": "",
                })
                counts["metadata.etl_rejects"] += 1
                out.write("_manifest.errors", {
                    "source_domain": reject.source_domain,
                    "source_file": reject.source_file,
                    "source_url": reject.source_url,
                    "error_code": reject.code,
                    "error_message": reject.message,
                })

        manifest = {
            "format_version": 3,
            "generated_at": generated_at,
            "input_contract": "filestorage/template_v2.json / organised JSON",
            "database_contract": "schema_supabase.sql v3",
            "input_directory": str(input_dir),
            "output_directory": str(output_dir),
            "canonical_source": canonical_source,
            "default_price_currency": currency,
            "records_discovered": len(paths),
            "records_written": len(records),
            "records_rejected": len(rejects),
            "canonical_records_selected": len(canonical_record_by_product),
            "marketplace_listings": sum(1 for r in records if r.source_domain != canonical_source),
            "companies": counts["catalog.companies"],
            "products": counts["catalog.products"],
            "rows_by_table": counts,
            "import_order": IMPORT_ORDER,
            "csv_null_convention": "Nullable values are written as empty CSV fields.",
            "identity_strategy": (
                "Identity/FK columns are populated explicitly with deterministic positive 63-bit BIGINTs. "
                "The SQL schema uses GENERATED BY DEFAULT AS IDENTITY, so explicit IDs are valid."
            ),
            "price_note": (
                "template_v2 stores numeric prices without currency; listing_prices uses the --currency value "
                f"({currency} for this run)."
            ),
            "files": sorted(
                str(path.relative_to(temp_root).as_posix())
                for path in temp_root.rglob("*") if path.is_file()
            ),
        }
        write_json(temp_root / "_manifest" / "manifest.json", manifest)
        replace_output_tree(temp_root, output_dir)
        return manifest
    except Exception:
        if temp_root.exists():
            shutil.rmtree(temp_root, ignore_errors=True)
        raise


