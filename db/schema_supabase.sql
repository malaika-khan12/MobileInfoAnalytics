-- Table: specs.spec_platform
CREATE TABLE IF NOT EXISTS specs.spec_platform (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    operating_system TEXT,
    chipset_name TEXT,
    chipset_node_nm INT,
    cpu_description TEXT,
