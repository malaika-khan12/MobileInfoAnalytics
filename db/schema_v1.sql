        execute format($ddl$
            create table if not exists %1$I.body (
                body_id bigint primary key
                    references %1$I.secondary_info (body_id) on delete cascade,
                dimensions text,
                weight text,
                build text,
                sim text,
                protection text
            )
        $ddl$, source_schema);

        execute format($ddl$
            create table if not exists %1$I.display (
