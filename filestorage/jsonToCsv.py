def canonical_site(value: str) -> str:
    host = str(value).strip().lower().split("@")[-1].split(":")[0]
    return re.sub(r"^www\.", "", host)


def canonicalize_url(value: Any, expected_site: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ConversionError("MISSING_URL", "URL is required in organised template_v2 JSON")
    parsed = urlparse(value.strip())
    if parsed.scheme.lower() not in {"http", "https"} or not parsed.netloc:
        raise ConversionError("INVALID_URL", f"Not a valid HTTP(S) URL: {value!r}")
    actual_site = canonical_site(parsed.netloc)
    if expected_site and actual_site != expected_site:
        raise ConversionError(
            "WRONG_URL_SITE",
            f"URL domain {actual_site!r} does not match source folder {expected_site!r}",
        )
    host = parsed.netloc.lower()
    return urlunparse(("https", host, parsed.path, "", parsed.query, ""))


def clean_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, (dict, list)):
        return compact_json(value)
    return SPACE_RE.sub(" ", str(value)).strip()


def required_text(value: Any, field: str) -> str:
    text = clean_text(value)
    if not text:
        raise ConversionError("MISSING_FIELD", f"{field} is required")
    return text


def compact_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)


def section(payload: Mapping[str, Any], name: str) -> Mapping[str, Any]:
    value = payload.get(name)
    return value if isinstance(value, Mapping) else {}


def nested_section(payload: Mapping[str, Any], first: str, second: str) -> Mapping[str, Any]:
    parent = section(payload, first)
    value = parent.get(second)
    return value if isinstance(value, Mapping) else {}


def as_list(value: Any) -> list[Any]:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def bool_value(value: Any, default: bool = False) -> bool:
    if value is None:
        return default
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return value != 0
    text = str(value).strip().lower()
    if text in {"1", "true", "t", "yes", "y", "on", "supported"}:
        return True
    if text in {"0", "false", "f", "no", "n", "off", "none", "unsupported"}:
        return False
    return default


def bool_csv(value: Any, default: bool = False) -> str:
    return "true" if bool_value(value, default) else "false"


def number_value(value: Any, default: int | float = 0) -> int | float:
    if value is None or isinstance(value, bool):
        return default
    if isinstance(value, (int, float)):
        return value
    text = str(value).strip().replace(",", "")
    try:
        result = float(text)
    except ValueError:
        match = re.search(r"[-+]?\d+(?:\.\d+)?", text)
        if not match:
            return default
        result = float(match.group(0))
    return int(result) if result.is_integer() else result


def optional_number(value: Any) -> str | int | float:
    if value is None or value == "":
        return ""
    result = number_value(value, 0)
    return result


def int_value(value: Any, default: int = 0) -> int:
    return int(round(float(number_value(value, default))))


def release_values(payload: Mapping[str, Any]) -> tuple[int, str, str | int]:
    year = int_value(payload.get("Year"), 2014)
    if year < 1900 or year > 2200:
        year = 2014
    month = clean_text(payload.get("Month")).upper() or "DEC"
    if month not in MONTHS:
        month = "DEC"
    day_raw = payload.get("Day")
    if day_raw is None or day_raw == "":
        day: str | int = ""
    else:
        candidate = int_value(day_raw, 0)
        day = candidate if 1 <= candidate <= 31 else ""
    return year, month, day


def pg_text_array(value: Any) -> str:
    """Encode a Python list as a PostgreSQL TEXT[] array literal."""
    items = []
    for item in as_list(value):
        if item is None:
            continue
        text = clean_text(item)
        if not text:
            continue
        text = text.replace("\\", "\\\\").replace('"', '\\"')
        items.append(f'"{text}"')
    return "{" + ",".join(items) + "}"


def json_array(value: Any, fallback: list[Any] | None = None) -> str:
    items = value if isinstance(value, list) else (fallback if fallback is not None else [])
    return compact_json(items)


def normalize_space_casefold(value: str) -> str:
    return SPACE_RE.sub(" ", value).strip().casefold()


def slugify(value: str) -> str:
    normalized = unicodedata.normalize("NFKD", value)
    ascii_text = normalized.encode("ascii", "ignore").decode("ascii").lower()
    slug = SLUG_RE.sub("-", ascii_text).strip("-")
    if slug:
        return slug
    return "item-" + hashlib.sha256(value.encode("utf-8")).hexdigest()[:12]


def stable_bigint(namespace: str, key: str) -> int:
    """Stable positive 63-bit integer suitable for PostgreSQL BIGINT."""
    digest = hashlib.sha256(f"{namespace}\0{key}".encode("utf-8")).digest()
    value = int.from_bytes(digest[:8], "big") & ((1 << 63) - 1)
    return value or 1


def file_sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def display_name(company: str, mobile: str) -> str:
    if normalize_space_casefold(mobile).startswith(normalize_space_casefold(company) + " "):
        return mobile
    return f"{company} {mobile}".strip()


def positive_prices(value: Any) -> list[int | float]:
    result: list[int | float] = []
    for item in as_list(value):
        if isinstance(item, bool):
            continue
        parsed = number_value(item, -1)
        if float(parsed) > 0:
            result.append(parsed)
    return result


