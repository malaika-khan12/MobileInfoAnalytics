-- Table: specs.spec_memory
CREATE TABLE IF NOT EXISTS specs.spec_memory (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    card_slot TEXT,
    storage_ram_variants JSONB NOT NULL DEFAULT '[[0,0]]'::jsonb, -- e.g. [[128, 6], [256, 8]]
    technology TEXT
