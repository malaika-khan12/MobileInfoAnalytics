-- -------------------------------------------------------------------------
-- Repeated marketplace schema.  This helper is run once per allowlisted
-- schema and then removed.  Static names are supplied only by this migration.
-- -------------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE etl.create_source_tables(p_schema VARCHAR)
AS $$
DECLARE
    s VARCHAR(128);
BEGIN
    IF p_schema NOT IN ('daraz', 'mymobile', 'mega', 'whatamobile', 'whatmobile') THEN
        RAISE EXCEPTION 'Unsupported source schema: %', p_schema;
    END IF;
    s := QUOTE_IDENT(p_schema);

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.central_info (
        serial_number BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1) NOT NULL,
        product_id BIGINT NOT NULL REFERENCES original.central_info(serial_number),
        instance_number INTEGER NOT NULL,
        PRIMARY KEY (serial_number),
        UNIQUE (product_id, instance_number)
    ) DISTSTYLE AUTO SORTKEY (product_id, instance_number)';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.secondary_info (
        serial_number BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.central_info(serial_number),
        data_snapshot SMALLINT NOT NULL,
        data_snapshot_detail VARCHAR(5) NOT NULL,
        name VARCHAR(1024) NOT NULL,
        url VARCHAR(2048) NOT NULL UNIQUE,
        network_id BIGINT NOT NULL UNIQUE,
        launch_id BIGINT NOT NULL UNIQUE,
        body_id BIGINT NOT NULL UNIQUE,
        display_id BIGINT NOT NULL UNIQUE,
        platform_id BIGINT NOT NULL UNIQUE,
        memory_id BIGINT NOT NULL UNIQUE,
        camera_back_id BIGINT NOT NULL UNIQUE,
        camera_front_id BIGINT NOT NULL UNIQUE,
        sound_loudspeaker VARCHAR(65535),
        sound_cable_jack BOOLEAN NOT NULL DEFAULT TRUE,
        features_id BIGINT NOT NULL UNIQUE,
        battery_id BIGINT NOT NULL UNIQUE,
        colors SUPER,
        weight VARCHAR(1024) NOT NULL DEFAULT ''Weight Unknown'',
        price SUPER NOT NULL
    ) DISTSTYLE AUTO SORTKEY (data_snapshot, name)';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.network (
        network_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(network_id),
        "2g" BOOLEAN NOT NULL DEFAULT TRUE,
        "3g" BOOLEAN NOT NULL DEFAULT TRUE,
        "4g" BOOLEAN NOT NULL DEFAULT FALSE,
        "5g" BOOLEAN NOT NULL DEFAULT TRUE
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.launch (
        launch_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(launch_id),
        announced VARCHAR(65535), status VARCHAR(65535)
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.body (
        body_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(body_id),
        dimensions VARCHAR(65535), weight VARCHAR(65535), build VARCHAR(65535),
        sim VARCHAR(65535), protection VARCHAR(65535)
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.display (
        display_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(display_id),
        type VARCHAR(65535), size VARCHAR(65535), resolution VARCHAR(65535),
        protection VARCHAR(65535)
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.platform (
        platform_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(platform_id),
        os VARCHAR(65535), chipset VARCHAR(65535), cpu VARCHAR(65535), gpu VARCHAR(65535)
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.memory (
        memory_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(memory_id),
        card_slot VARCHAR(65535), technology VARCHAR(65535), types SUPER
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.camera_back (
        camera_back_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(camera_back_id),
        specifications SUPER, features VARCHAR(65535), video SUPER
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.camera_front (
        camera_front_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(camera_front_id),
        specifications SUPER, features VARCHAR(65535), video SUPER
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.features (
        features_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(features_id),
        wlan VARCHAR(65535), bluetooth VARCHAR(65535), positioning VARCHAR(65535),
        nfc BOOLEAN NOT NULL DEFAULT FALSE,
        infrared_port BOOLEAN NOT NULL DEFAULT FALSE,
        radio BOOLEAN NOT NULL DEFAULT TRUE,
        usb VARCHAR(65535),
        back_finger_print BOOLEAN NOT NULL DEFAULT FALSE,
        side_finger_print BOOLEAN NOT NULL DEFAULT FALSE,
        in_display_finger_print BOOLEAN NOT NULL DEFAULT FALSE,
        sensors VARCHAR(65535)
    ) DISTSTYLE AUTO';

    EXECUTE 'CREATE TABLE IF NOT EXISTS ' || s || '.battery (
        battery_id BIGINT NOT NULL PRIMARY KEY REFERENCES ' || s || '.secondary_info(battery_id),
        capacity VARCHAR(65535),
        wireless_charging BOOLEAN NOT NULL DEFAULT FALSE,
        charging SUPER
    ) DISTSTYLE AUTO';
END;
$$ LANGUAGE plpgsql;

CALL etl.create_source_tables('daraz');
CALL etl.create_source_tables('mymobile');
CALL etl.create_source_tables('mega');
CALL etl.create_source_tables('whatamobile');
CALL etl.create_source_tables('whatmobile');
