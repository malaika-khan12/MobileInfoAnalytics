create table if not exists original.central_info (
    serial_number bigint generated by default as identity primary key,
    data_snapshot timestamptz not null default clock_timestamp(),
    name text not null,
    url text not null,
    network_id bigint generated by default as identity not null unique,
    launch_id bigint generated by default as identity not null unique,
    body_id bigint generated by default as identity not null unique,
    display_id bigint generated by default as identity not null unique,
    platform_id bigint generated by default as identity not null unique,
    memory_id bigint generated by default as identity not null unique,
    camera_back_id bigint generated by default as identity not null unique,
    camera_front_id bigint generated by default as identity not null unique,
    sound_loudspeaker text,
    sound_cable_jack boolean not null default true,
    features_id bigint generated by default as identity not null unique,
    battery_id bigint generated by default as identity not null unique,
    colors text[] not null default '{}'::text[],
    weight text not null default 'Weight Unknown',
    price numeric(14,2)[] not null
        default array[-1.00]::numeric(14,2)[],
    constraint original_central_name_uq unique (name),
    constraint original_central_url_uq unique (url),
    constraint original_central_name_present_ck
        check (btrim(name) <> ''),
    constraint original_central_url_http_ck
        check (url ~* '^https?://'),
    constraint original_central_price_present_ck
        check (cardinality(price) >= 1),
    constraint original_central_price_no_nulls_ck
        check (array_position(price, null) is null),
    constraint original_central_colors_no_nulls_ck
        check (array_position(colors, null) is null)
);

