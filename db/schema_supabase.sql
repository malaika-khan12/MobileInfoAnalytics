-- =============================================================================
-- MobileInfoAnalytics - Supabase PostgreSQL Database Schema (v3)
-- Target: PostgreSQL 15+ / Supabase
-- Architecture: 4 Schemas (catalog, specs, listings, metadata) + staging & analytics
-- Based on template_v2 specification and multi-source cross-linking design.
-- Includes full Row Level Security (RLS) policies and Role Permissions.
-- =============================================================================

-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm"; -- For fuzzy name and alias matching

-- -----------------------------------------------------------------------------
-- Schemas
-- -----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS catalog;   -- Source-independent product & brand identity
CREATE SCHEMA IF NOT EXISTS specs;     -- Canonical GSMArena / best-known specifications
CREATE SCHEMA IF NOT EXISTS listings;  -- All marketplace listings with full per-listing specs
CREATE SCHEMA IF NOT EXISTS metadata;  -- Ingestion audit runs, rejects & quality scoring
CREATE SCHEMA IF NOT EXISTS staging;   -- Raw JSON staging & landing tables
CREATE SCHEMA IF NOT EXISTS analytics; -- Stable analytical views for comparison & insights
CREATE SCHEMA IF NOT EXISTS etl;       -- Ingestion functions, procedures & pipelines

-- =============================================================================
-- 1. SCHEMA: catalog (Product & Brand Identity)
-- =============================================================================

-- Table: catalog.companies (Manufacturer / Brand Master)
CREATE TABLE IF NOT EXISTS catalog.companies (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name TEXT NOT NULL,
    company_slug TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE catalog.companies IS 'Normalized mobile brand/manufacturer master list.';
COMMENT ON COLUMN catalog.companies.company_slug IS 'URL-safe lowercased slug (e.g., xiaomi, samsung, apple).';

-- Table: catalog.products (Central Abstract Product Hub)
CREATE TABLE IF NOT EXISTS catalog.products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES catalog.companies(company_id) ON DELETE RESTRICT,
    mobile_name TEXT NOT NULL,
    product_slug TEXT NOT NULL UNIQUE,
    created_by_source TEXT NOT NULL DEFAULT 'unknown',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE catalog.products IS 'The abstract central mobile phone entity. Independent of any single website.';
COMMENT ON COLUMN catalog.products.product_slug IS 'Universal matching slug (e.g., xiaomi-redmi-note-14-4g).';
COMMENT ON COLUMN catalog.products.created_by_source IS 'Tracks which site (e.g. gsmarena, daraz, whatmobile) first discovered this phone.';

-- Table: catalog.product_aliases (Cross-Site Name Disambiguation & Alias Mapping)
CREATE TABLE IF NOT EXISTS catalog.product_aliases (
    alias_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES catalog.products(product_id) ON DELETE CASCADE,
    alias_name TEXT NOT NULL,
    alias_slug TEXT NOT NULL UNIQUE,
    source_domain TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE catalog.product_aliases IS 'Alternative titles across websites mapped to the canonical product_id.';

CREATE INDEX IF NOT EXISTS idx_products_company_id ON catalog.products(company_id);
CREATE INDEX IF NOT EXISTS idx_products_slug ON catalog.products(product_slug);
CREATE INDEX IF NOT EXISTS idx_aliases_product_id ON catalog.product_aliases(product_id);
CREATE INDEX IF NOT EXISTS idx_aliases_slug ON catalog.product_aliases(alias_slug);


-- =============================================================================
-- 2. SCHEMA: specs (Canonical / Best-Known Specifications)
-- =============================================================================

-- Table: specs.product_specs (Central Canonical Header)
CREATE TABLE IF NOT EXISTS specs.product_specs (
    product_id BIGINT PRIMARY KEY REFERENCES catalog.products(product_id) ON DELETE CASCADE,
    release_year SMALLINT NOT NULL DEFAULT 2014,
    release_month VARCHAR(3) NOT NULL DEFAULT 'DEC',
    release_day SMALLINT,
    announced_text TEXT,
    status_text TEXT,
    colors TEXT[] DEFAULT '{}',
    has_loudspeaker BOOLEAN NOT NULL DEFAULT TRUE,
    has_3_5mm_jack BOOLEAN NOT NULL DEFAULT TRUE,
    specs_source TEXT NOT NULL DEFAULT 'gsmarena.com',
    last_updated TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE specs.product_specs IS 'Canonical product specs header (1:1 with catalog.products).';

-- Table: specs.spec_network
CREATE TABLE IF NOT EXISTS specs.spec_network (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    supports_2g BOOLEAN NOT NULL DEFAULT TRUE,
    supports_3g BOOLEAN NOT NULL DEFAULT TRUE,
    supports_4g BOOLEAN NOT NULL DEFAULT FALSE,
    supports_5g BOOLEAN NOT NULL DEFAULT FALSE
);

-- Table: specs.spec_body
CREATE TABLE IF NOT EXISTS specs.spec_body (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    dim_length_mm NUMERIC(6,2) NOT NULL DEFAULT 50.0,
    dim_width_mm NUMERIC(6,2) NOT NULL DEFAULT 50.0,
    dim_depth_mm NUMERIC(5,2) NOT NULL DEFAULT 5.0,
