-- Table: specs.spec_display
CREATE TABLE IF NOT EXISTS specs.spec_display (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    screen_technology TEXT NOT NULL DEFAULT 'LCD', -- 'CRT', 'LCD', 'LED', 'AMOLED', 'OLED'
