-- Table: specs.spec_battery
CREATE TABLE IF NOT EXISTS specs.spec_battery (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    capacity_mah INT NOT NULL DEFAULT 0,
    has_wireless_charging BOOLEAN NOT NULL DEFAULT FALSE,
    charging_specs TEXT[] DEFAULT '{}'
