-- -------------------------------------------------------------------------
-- Marketplace/source schemas.  All five have the same shape.  A listing is
-- first stored in secondary_info; central_info is its optional-to-create but
-- strict-when-present link to a canonical original product.  This permits
-- ingestion before product matching without weakening the requested NOT NULL
-- product_id rule.
-- -------------------------------------------------------------------------

do $schema$
declare
    source_schema text;
begin
    foreach source_schema in array
        array['daraz', 'mymobile', 'mega', 'whatamobile', 'whatmobile']
    loop
        execute format($ddl$
            create table if not exists %1$I.secondary_info (
                serial_number bigint generated by default as identity primary key,
                data_snapshot timestamptz not null default clock_timestamp(),
                name text not null,
                url text not null,
                network_id bigint generated by default as identity not null unique,
