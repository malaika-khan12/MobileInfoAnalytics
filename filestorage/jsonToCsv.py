class CsvTree:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.stack = ExitStack()
        self.writers: dict[str, csv.DictWriter] = {}
        self.files: list[str] = []

    def __enter__(self) -> "CsvTree":
        self.root.mkdir(parents=True, exist_ok=True)
        for table, fields in TABLE_FIELDS.items():
            schema, name = table.split(".", 1)
            self._open(table, self.root / schema / f"{name}.csv", fields)
        self._open("_manifest.records", self.root / "_manifest" / "records.csv", MANIFEST_FIELDS)
        self._open("_manifest.errors", self.root / "_manifest" / "errors.csv", ERROR_FIELDS)
        return self

    def _open(self, key: str, path: Path, fields: Sequence[str]) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        handle = self.stack.enter_context(path.open("w", encoding="utf-8", newline=""))
        writer = csv.DictWriter(handle, fieldnames=list(fields), extrasaction="raise")
        writer.writeheader()
        self.writers[key] = writer
        self.files.append(path.relative_to(self.root).as_posix())

    def write(self, table: str, row: Mapping[str, Any]) -> None:
        self.writers[table].writerow(row)

    def write_many(self, table: str, rows: Iterable[Mapping[str, Any]]) -> None:
        for row in rows:
            self.write(table, row)

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> bool:
        self.stack.close()
        return False


def replace_output_tree(temp_root: Path, output_dir: Path) -> None:
    if output_dir.exists():
        shutil.rmtree(output_dir)
    os.replace(temp_root, output_dir)


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")


