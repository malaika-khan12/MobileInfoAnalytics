create table if not exists warehouse.ingest_runs (
    run_id bigint generated by default as identity primary key,
    loader_name text not null default 'filestorage/csvToDataBase.py',
    target_kind text not null default 'supabase',
    source_manifest text,
    started_at timestamptz not null default clock_timestamp(),
    finished_at timestamptz,
    rows_attempted bigint not null default 0,
    rows_succeeded bigint not null default 0,
    rows_failed bigint not null default 0,
    status text not null default 'running',
    details jsonb not null default '{}'::jsonb,
    constraint ingest_runs_status_ck
        check (status in ('running', 'completed', 'completed_with_errors', 'failed')),
    constraint ingest_runs_counts_ck
        check (
            rows_attempted >= 0
            and rows_succeeded >= 0
            and rows_failed >= 0
        )
);

create table if not exists warehouse.raw_ingest (
    raw_id bigint generated by default as identity primary key,
    source_schema text not null,
    source_url text not null,
    source_file text,
    data_snapshot timestamptz not null,
    payload jsonb not null,
    payload_md5 text generated always as (md5(payload::text)) stored,
    ingested_at timestamptz not null default clock_timestamp(),
    constraint raw_ingest_source_schema_ck check (
        source_schema in (
            'original', 'daraz', 'mymobile', 'mega',
            'whatamobile', 'whatmobile'
        )
    ),
    constraint raw_ingest_url_http_ck check (source_url ~* '^https?://'),
    constraint raw_ingest_payload_object_ck
        check (jsonb_typeof(payload) = 'object'),
    constraint raw_ingest_event_uq
        unique (source_schema, source_url, data_snapshot, payload_md5)
);

create table if not exists warehouse.price_history (
    price_history_id bigint generated by default as identity primary key,
    source_schema text not null,
    source_serial_number bigint not null,
    product_id bigint
        references original.central_info (serial_number) on delete set null,
    source_url text not null,
    product_name text not null,
    data_snapshot timestamptz not null,
    price_position smallint not null,
    amount numeric(14,2) not null,
    currency_code text,
    ingested_at timestamptz not null default clock_timestamp(),
    constraint price_history_source_schema_ck check (
        source_schema in (
            'original', 'daraz', 'mymobile', 'mega',
            'whatamobile', 'whatmobile'
        )
    ),
    constraint price_history_position_ck check (price_position > 0),
    constraint price_history_amount_ck check (amount > 0),
    constraint price_history_currency_ck check (
        currency_code is null or currency_code ~ '^[A-Z]{3}$'
    ),
    constraint price_history_event_uq unique (
        source_schema, source_url, data_snapshot, price_position
    )
);

create table if not exists warehouse.etl_rejects (
