#!/usr/bin/env python3
"""Convert template_v2 organised mobile JSON files into Supabase v3 CSV tables.

Input contract
--------------
The input is the output of ``filestorage/organise_with_llm.py`` and therefore
uses the organised/template_v2 shape.  By default records are read from:

    filestorage/mobiles_organised/<source-domain>/*.json

Output contract
---------------
The output hierarchy mirrors ``schema_supabase.sql`` exactly:

    filestorage/csvs/catalog/*.csv
    filestorage/csvs/specs/*.csv
    filestorage/csvs/listings/*.csv
    filestorage/csvs/metadata/*.csv
    filestorage/csvs/staging/*.csv
    filestorage/csvs/_manifest/*

GSMArena is treated as the canonical specification source and populates the
``specs`` tables.  Other sources populate ``listings``.  Every valid JSON file
also receives a row in ``staging.raw_json_records`` and a data-quality row.

The database uses BIGINT identity keys.  CSV conversion happens before a
PostgreSQL session exists, so this script generates deterministic positive
BIGINT IDs from stable natural keys (company slug, product slug, source URL,
etc.).  The schema uses ``GENERATED BY DEFAULT AS IDENTITY``, which permits
explicit values during bulk loading while preserving all foreign-key links.

Only Python's standard library is required.  The script is cross-platform and
works from Windows, Linux and WSL.
"""

