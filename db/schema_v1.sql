CREATE TABLE IF NOT EXISTS warehouse.raw_ingest (
    raw_id BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1) NOT NULL,
    record_key CHAR(64) NOT NULL,
    source_schema VARCHAR(32) NOT NULL,
    source_url VARCHAR(2048) NOT NULL,
    source_file VARCHAR(2048) NOT NULL,
    data_snapshot SMALLINT,
    data_snapshot_detail VARCHAR(5),
    snapshot_source VARCHAR(32),
    file_sha256 CHAR(64) NOT NULL,
    completeness_score DECIMAL(6,5),
    payload SUPER NOT NULL,
    loaded_at TIMESTAMP NOT NULL DEFAULT GETDATE(),
    PRIMARY KEY (raw_id),
    UNIQUE (source_schema, source_url, file_sha256)
) DISTSTYLE AUTO SORTKEY (loaded_at, source_schema);

CREATE TABLE IF NOT EXISTS warehouse.price_history (
    price_id BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1) NOT NULL,
    product_id BIGINT NOT NULL REFERENCES original.central_info(serial_number),
    source_schema VARCHAR(32) NOT NULL,
    source_serial_number BIGINT NOT NULL,
    source_url VARCHAR(2048) NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    observed_at TIMESTAMP NOT NULL DEFAULT GETDATE(),
    data_snapshot SMALLINT NOT NULL,
    data_snapshot_detail VARCHAR(5) NOT NULL,
    amount DECIMAL(18,2) NOT NULL,
    currency_code VARCHAR(3),
    PRIMARY KEY (price_id)
) DISTSTYLE AUTO SORTKEY (product_id, observed_at);

CREATE TABLE IF NOT EXISTS warehouse.etl_rejects (
    reject_id BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1) NOT NULL,
    record_key CHAR(64),
    source_schema VARCHAR(32) NOT NULL,
    source_url VARCHAR(2048),
    source_file VARCHAR(2048),
    reason_code VARCHAR(64) NOT NULL,
    reason_detail VARCHAR(65535),
    payload SUPER,
    rejected_at TIMESTAMP NOT NULL DEFAULT GETDATE(),
    resolved_at TIMESTAMP,
    resolution_detail VARCHAR(65535),
    PRIMARY KEY (reject_id)
) DISTSTYLE AUTO SORTKEY (rejected_at, source_schema);

CREATE TABLE IF NOT EXISTS warehouse.load_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1) NOT NULL,
    started_at TIMESTAMP NOT NULL DEFAULT GETDATE(),
    finished_at TIMESTAMP,
    staged_count BIGINT NOT NULL DEFAULT 0,
    loaded_count BIGINT NOT NULL DEFAULT 0,
    rejected_count BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'running',
    PRIMARY KEY (run_id)
) DISTSTYLE AUTO SORTKEY (started_at);
