CREATE TABLE IF NOT EXISTS original.central_info (
    serial_number BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1) NOT NULL,
    data_snapshot SMALLINT NOT NULL
        DEFAULT (DATE_PART(year, CURRENT_DATE)),
    data_snapshot_detail VARCHAR(5) NOT NULL
        DEFAULT TO_CHAR(CURRENT_DATE, 'MM-DD'),
    snapshot_source VARCHAR(16) NOT NULL DEFAULT 'current_utc',
    name VARCHAR(1024) NOT NULL,
    url VARCHAR(2048) NOT NULL,
    network_id BIGINT NOT NULL,
    launch_id BIGINT NOT NULL,
    body_id BIGINT NOT NULL,
    display_id BIGINT NOT NULL,
    platform_id BIGINT NOT NULL,
    memory_id BIGINT NOT NULL,
    camera_back_id BIGINT NOT NULL,
    camera_front_id BIGINT NOT NULL,
    sound_loudspeaker VARCHAR(65535),
    sound_cable_jack BOOLEAN NOT NULL DEFAULT TRUE,
    features_id BIGINT NOT NULL,
    battery_id BIGINT NOT NULL,
    colors SUPER,
    weight VARCHAR(1024) NOT NULL DEFAULT 'Weight Unknown',
    price SUPER NOT NULL,
    PRIMARY KEY (serial_number),
    UNIQUE (name),
    UNIQUE (url),
    UNIQUE (network_id),
    UNIQUE (launch_id),
    UNIQUE (body_id),
    UNIQUE (display_id),
    UNIQUE (platform_id),
    UNIQUE (memory_id),
    UNIQUE (camera_back_id),
    UNIQUE (camera_front_id),
    UNIQUE (features_id),
    UNIQUE (battery_id)
) DISTSTYLE AUTO SORTKEY (data_snapshot, name);

