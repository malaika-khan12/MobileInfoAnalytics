    has_esim BOOLEAN NOT NULL DEFAULT FALSE,
    ip_rating TEXT,
    is_water_resistant BOOLEAN NOT NULL DEFAULT FALSE,
    is_dust_resistant BOOLEAN NOT NULL DEFAULT TRUE
