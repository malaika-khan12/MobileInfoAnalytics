class ConversionError(ValueError):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


@dataclass
class PhoneRecord:
    path: Path
    source_file: str
    source_domain: str
    source_url: str
    payload: dict[str, Any]
    raw_bytes: bytes
    file_sha256: str
    company_name: str
    mobile_name: str
    company_identity: str
    product_identity: str
    company_slug: str = ""
    product_slug: str = ""
    company_id: int = 0
    product_id: int = 0
    listing_id: int | None = None
    instance_number: int | None = None
    completeness_populated: int = 0
    completeness_total: int = 0

    @property
    def record_key(self) -> str:
        return hashlib.sha256(
            f"{self.source_domain}\0{self.source_url}".encode("utf-8")
        ).hexdigest()

    @property
    def completeness_pct(self) -> float:
        if not self.completeness_total:
            return 0.0
        return round(100.0 * self.completeness_populated / self.completeness_total, 2)

    @property
    def is_canonical(self) -> bool:
        return self.source_domain == DEFAULT_CANONICAL_SOURCE


