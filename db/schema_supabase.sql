-- =============================================================================
-- 3. SCHEMA: metadata (Audit Runs, Logs & Reject Tracking)
-- =============================================================================

-- Table: metadata.scrape_runs
CREATE TABLE IF NOT EXISTS metadata.scrape_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_domain TEXT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    records_processed INT NOT NULL DEFAULT 0,
    records_succeeded INT NOT NULL DEFAULT 0,
    records_failed INT NOT NULL DEFAULT 0,
    run_status TEXT NOT NULL DEFAULT 'running'
);

-- Table: metadata.etl_rejects
CREATE TABLE IF NOT EXISTS metadata.etl_rejects (
    reject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scrape_run_id BIGINT REFERENCES metadata.scrape_runs(run_id) ON DELETE SET NULL,
    source_domain TEXT NOT NULL,
    source_url TEXT,
    source_file TEXT,
    reject_reason TEXT NOT NULL,
    reject_detail TEXT,
    raw_payload JSONB,
    rejected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ,
    resolution_detail TEXT
);

-- Table: metadata.data_quality
CREATE TABLE IF NOT EXISTS metadata.data_quality (
    score_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES catalog.products(product_id) ON DELETE CASCADE,
    listing_id BIGINT,
    source_domain TEXT NOT NULL,
    completeness_pct NUMERIC(5,2) NOT NULL,
    fields_populated INT NOT NULL,
    fields_total INT NOT NULL,
    scored_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =============================================================================
-- 4. SCHEMA: listings (Marketplace Listings & Individual Scraped Specs)
-- =============================================================================

-- Table: listings.market_listings (Master Listing Record)
CREATE TABLE IF NOT EXISTS listings.market_listings (
    listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES catalog.products(product_id) ON DELETE CASCADE,
    instance_number INT NOT NULL DEFAULT 1,
    source_domain TEXT NOT NULL, -- 'daraz.pk', 'whatmobile.com.pk', 'mega.pk', 'mymobile.pk', 'gsmarena.com'
    source_url TEXT NOT NULL UNIQUE,
    listing_title TEXT NOT NULL,
    announced_text TEXT,
    status_text TEXT,
    release_year SMALLINT NOT NULL DEFAULT 2014,
    release_month VARCHAR(3) NOT NULL DEFAULT 'DEC',
    release_day SMALLINT,
    colors TEXT[] DEFAULT '{}',
    has_loudspeaker BOOLEAN NOT NULL DEFAULT TRUE,
    has_3_5mm_jack BOOLEAN NOT NULL DEFAULT TRUE,
    raw_payload JSONB,
    scrape_run_id BIGINT REFERENCES metadata.scrape_runs(run_id) ON DELETE SET NULL,
    scraped_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_product_source_instance UNIQUE (product_id, source_domain, instance_number)
);

COMMENT ON TABLE listings.market_listings IS 'Every individual scraped listing per website with instance tracking.';
COMMENT ON COLUMN listings.market_listings.instance_number IS 'Instance sequence per (product, source_domain).';

-- Table: listings.listing_prices (Structured Prices with Currency)
CREATE TABLE IF NOT EXISTS listings.listing_prices (
    price_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings.market_listings(listing_id) ON DELETE CASCADE,
    currency_code VARCHAR(3) NOT NULL DEFAULT 'PKR', -- 'USD', 'EUR', 'GBP', 'PKR'
    amount NUMERIC(14,2) NOT NULL,
    price_index INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_listing_currency_idx UNIQUE (listing_id, currency_code, price_index)
);

-- Table: listings.listing_network
