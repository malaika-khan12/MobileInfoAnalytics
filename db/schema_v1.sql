-- Every listing, including records that have not yet been matched to a
-- canonical GSMArena product.  Price arrays retain their original order.
create or replace view warehouse.current_listings as
select
    'original'::text as source_schema,
    c.serial_number as source_serial_number,
    c.serial_number as product_id,
    1::integer as instance_number,
    c.data_snapshot,
    c.name,
    c.url,
    c.price
from original.central_info as c
union all
select 'daraz', s.serial_number, c.product_id, c.instance_number,
       s.data_snapshot, s.name, s.url, s.price
from daraz.secondary_info as s
left join daraz.central_info as c using (serial_number)
union all
select 'mymobile', s.serial_number, c.product_id, c.instance_number,
       s.data_snapshot, s.name, s.url, s.price
from mymobile.secondary_info as s
left join mymobile.central_info as c using (serial_number)
union all
select 'mega', s.serial_number, c.product_id, c.instance_number,
       s.data_snapshot, s.name, s.url, s.price
from mega.secondary_info as s
left join mega.central_info as c using (serial_number)
union all
select 'whatamobile', s.serial_number, c.product_id, c.instance_number,
       s.data_snapshot, s.name, s.url, s.price
from whatamobile.secondary_info as s
left join whatamobile.central_info as c using (serial_number)
union all
select 'whatmobile', s.serial_number, c.product_id, c.instance_number,
       s.data_snapshot, s.name, s.url, s.price
from whatmobile.secondary_info as s
left join whatmobile.central_info as c using (serial_number);

create or replace view warehouse.current_prices as
select
    listing.source_schema,
    listing.source_serial_number,
    listing.product_id,
    listing.instance_number,
    listing.data_snapshot,
    listing.name,
    listing.url,
    price.price_position,
    price.amount,
    case
        when listing.source_schema = 'original' then null
        else 'PKR'
    end as currency_code
from warehouse.current_listings as listing
cross join lateral unnest(listing.price) with ordinality
    as price(amount, price_position)
where price.amount > 0;

comment on column warehouse.current_prices.currency_code is
    'Marketplace prices are PKR. GSMArena Price[] positions can contain multiple currencies, so original rows intentionally remain NULL rather than being mislabeled.';

-- Custom schemas are private by default.  The functions file grants only the
-- narrow RPC functions to Supabase service_role; no browser role receives
-- direct table access.
do $security$
declare
    object_schema text;
    role_name text;
begin
    foreach object_schema in array array[
        'original', 'daraz', 'mymobile', 'mega',
        'whatamobile', 'whatmobile', 'warehouse', 'etl_private', 'api'
    ]
    loop
        execute format('revoke all on schema %I from public', object_schema);
        execute format('revoke all on all tables in schema %I from public', object_schema);
        execute format('revoke all on all sequences in schema %I from public', object_schema);
        execute format(
            'alter default privileges in schema %I revoke all on tables from public',
            object_schema
        );
        execute format(
            'alter default privileges in schema %I revoke all on sequences from public',
            object_schema
        );
        execute format(
            'alter default privileges in schema %I revoke execute on functions from public',
            object_schema
        );

        foreach role_name in array array['anon', 'authenticated']
        loop
            if exists (select 1 from pg_roles where rolname = role_name) then
                execute format(
                    'revoke all on schema %I from %I', object_schema, role_name
                );
                execute format(
                    'revoke all on all tables in schema %I from %I',
                    object_schema, role_name
                );
                execute format(
                    'revoke all on all sequences in schema %I from %I',
                    object_schema, role_name
                );
            end if;
        end loop;
    end loop;

    foreach object_schema in array array[
        'original', 'daraz', 'mymobile', 'mega',
        'whatamobile', 'whatmobile'
    ]
    loop
        execute format('alter table %I.central_info enable row level security', object_schema);
        if object_schema <> 'original' then
            execute format('alter table %I.secondary_info enable row level security', object_schema);
        end if;
        execute format('alter table %I.network enable row level security', object_schema);
        execute format('alter table %I.launch enable row level security', object_schema);
        execute format('alter table %I.body enable row level security', object_schema);
        execute format('alter table %I.display enable row level security', object_schema);
        execute format('alter table %I.platform enable row level security', object_schema);
        execute format('alter table %I.memory enable row level security', object_schema);
        execute format('alter table %I.camera_back enable row level security', object_schema);
        execute format('alter table %I.camera_front enable row level security', object_schema);
        execute format('alter table %I.features enable row level security', object_schema);
        execute format('alter table %I.battery enable row level security', object_schema);
    end loop;

    alter table warehouse.ingest_runs enable row level security;
    alter table warehouse.raw_ingest enable row level security;
    alter table warehouse.price_history enable row level security;
    alter table warehouse.etl_rejects enable row level security;
end
$security$;

commit;
