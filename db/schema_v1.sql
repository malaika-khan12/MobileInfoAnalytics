-- MobileInfoAnalytics database schema v1
-- Target: PostgreSQL 15+ as provided by Supabase.
--
-- The six source schemas preserve the table layout requested in
-- database_layout.txt.  The warehouse schema adds two things that the source
-- layout cannot safely represent on its own: the immutable raw payload and an
-- append-only price history.  This keeps re-scrapes useful for historical BI
-- while the source tables continue to represent the latest known state.

begin;

create schema if not exists original;
create schema if not exists daraz;
create schema if not exists mymobile;
create schema if not exists mega;
create schema if not exists whatamobile;
create schema if not exists whatmobile;
create schema if not exists warehouse;
create schema if not exists etl_private;
create schema if not exists api;

comment on schema original is
    'Canonical GSMArena product specification records.';
comment on schema warehouse is
    'Immutable landing records, historical prices, and cross-source views.';
comment on schema etl_private is
    'Internal helpers used by the versioned ingestion functions.';
comment on schema api is
    'Explicit Supabase RPC surface for ingestion, matching, and analytics.';

-- -------------------------------------------------------------------------
-- Canonical GSMArena tables
