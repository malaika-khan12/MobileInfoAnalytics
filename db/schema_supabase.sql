-- Table: specs.spec_camera_main
CREATE TABLE IF NOT EXISTS specs.spec_camera_main (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    sensor_specs TEXT[] DEFAULT '{}',
    photo_features TEXT,
    video_modes TEXT[] DEFAULT '{}'
);

-- Table: specs.spec_camera_selfie
CREATE TABLE IF NOT EXISTS specs.spec_camera_selfie (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    sensor_specs TEXT[] DEFAULT '{}',
    video_modes TEXT[] DEFAULT '{}'
);

-- Table: specs.spec_connectivity
CREATE TABLE IF NOT EXISTS specs.spec_connectivity (
    product_id BIGINT PRIMARY KEY REFERENCES specs.product_specs(product_id) ON DELETE CASCADE,
    wifi_standards TEXT,
    bluetooth_version TEXT,
    positioning_systems TEXT,
    has_nfc BOOLEAN NOT NULL DEFAULT FALSE,
    has_infrared BOOLEAN NOT NULL DEFAULT FALSE,
    has_fm_radio BOOLEAN NOT NULL DEFAULT TRUE,
    has_usb_a BOOLEAN NOT NULL DEFAULT FALSE,
    has_usb_b BOOLEAN NOT NULL DEFAULT FALSE,
    has_micro_usb BOOLEAN NOT NULL DEFAULT TRUE,
    has_usb_c BOOLEAN NOT NULL DEFAULT FALSE,
    has_fp_rear BOOLEAN NOT NULL DEFAULT FALSE,
    has_fp_side BOOLEAN NOT NULL DEFAULT FALSE,
    has_fp_under_display BOOLEAN NOT NULL DEFAULT FALSE
