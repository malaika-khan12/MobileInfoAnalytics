def path_value(payload: Mapping[str, Any], path: Sequence[str]) -> Any:
    current: Any = payload
    for key in path:
        if not isinstance(current, Mapping) or key not in current:
            return None
        current = current[key]
    return current


def has_semantic_value(value: Any) -> bool:
    if value is None:
        return False
    if isinstance(value, str):
        return bool(value.strip())
    if isinstance(value, (list, dict)):
        return bool(value)
    return True


def quality_counts(payload: Mapping[str, Any]) -> tuple[int, int]:
    populated = sum(has_semantic_value(path_value(payload, path)) for path in QUALITY_PATHS)
    return populated, len(QUALITY_PATHS)


