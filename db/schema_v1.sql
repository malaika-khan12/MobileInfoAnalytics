-- MobileInfoAnalytics database schema v1
-- Target: Amazon Redshift (provisioned or Serverless).
--
-- GSMArena is the canonical product authority.  data_snapshot is a release
-- year and data_snapshot_detail preserves the available month precision as
-- MM or MM-DD.  Marketplace tables receive both values only through their
-- product_id relationship to original.central_info.
--
-- Redshift primary, unique, and foreign-key constraints are informational.
-- db/functions_v1.sql therefore performs the matching, de-duplication, and
-- referential-integrity work before inserting rows.

CREATE SCHEMA IF NOT EXISTS original;
CREATE SCHEMA IF NOT EXISTS daraz;
CREATE SCHEMA IF NOT EXISTS mymobile;
CREATE SCHEMA IF NOT EXISTS mega;
CREATE SCHEMA IF NOT EXISTS whatamobile;
CREATE SCHEMA IF NOT EXISTS whatmobile;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS warehouse;
CREATE SCHEMA IF NOT EXISTS analytics;
CREATE SCHEMA IF NOT EXISTS etl;

