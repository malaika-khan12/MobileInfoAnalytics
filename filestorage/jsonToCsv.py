def load_phone_json(path: Path, input_dir: Path) -> PhoneRecord:
    source_domain = canonical_site(path.parent.name)
    source_file = path.relative_to(input_dir).as_posix()
    try:
        raw = path.read_bytes()
        payload = json.loads(raw.decode("utf-8-sig"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ConversionError("INVALID_JSON", f"{source_file}: {exc}") from exc
    if not isinstance(payload, dict):
        raise ConversionError("INVALID_PAYLOAD", f"{source_file}: top-level JSON must be an object")

    company = required_text(payload.get("CompanyName"), "CompanyName")
    mobile = required_text(payload.get("MobileName"), "MobileName")
    url = canonicalize_url(payload.get("URL"), source_domain)
    populated, total = quality_counts(payload)
    return PhoneRecord(
        path=path,
        source_file=source_file,
        source_domain=source_domain,
        source_url=url,
        payload=payload,
        raw_bytes=raw,
        file_sha256=file_sha256(raw),
        company_name=company,
        mobile_name=mobile,
        company_identity=normalize_space_casefold(company),
        product_identity=f"{normalize_space_casefold(company)}\0{normalize_space_casefold(mobile)}",
        completeness_populated=populated,
        completeness_total=total,
    )


def discover_paths(input_dir: Path, selected_sites: set[str] | None) -> list[Path]:
    if not input_dir.is_dir():
        raise FileNotFoundError(f"Input directory does not exist: {input_dir}")
    paths: list[Path] = []
    for site_dir in sorted(p for p in input_dir.iterdir() if p.is_dir()):
        site = canonical_site(site_dir.name)
        if selected_sites is not None and site not in selected_sites:
            continue
        for path in sorted(site_dir.glob("*.json")):
            if not path.name.startswith("_"):
                paths.append(path)
    return paths


def assign_identity_slugs(records: list[PhoneRecord]) -> None:
    company_names: dict[str, str] = {}
    for record in records:
        existing = company_names.get(record.company_identity)
        if existing is None or record.company_name < existing:
            company_names[record.company_identity] = record.company_name

    company_base_groups: dict[str, list[str]] = {}
    for identity, name in company_names.items():
        company_base_groups.setdefault(slugify(name), []).append(identity)

    company_slug_by_identity: dict[str, str] = {}
    for base, identities in company_base_groups.items():
        for identity in sorted(identities):
            company_slug_by_identity[identity] = (
                base if len(identities) == 1
                else f"{base}-{hashlib.sha256(identity.encode()).hexdigest()[:8]}"
            )

    product_groups: dict[str, list[str]] = {}
    product_base_by_identity: dict[str, str] = {}
    for record in records:
        company_slug = company_slug_by_identity[record.company_identity]
        base = f"{company_slug}-{slugify(record.mobile_name)}"
        product_base_by_identity[record.product_identity] = base
        product_groups.setdefault(base, []).append(record.product_identity)

    product_slug_by_identity: dict[str, str] = {}
    for base, identities_raw in product_groups.items():
        identities = sorted(set(identities_raw))
        for identity in identities:
            product_slug_by_identity[identity] = (
                base if len(identities) == 1
                else f"{base}-{hashlib.sha256(identity.encode()).hexdigest()[:8]}"
            )

    seen_ids: dict[int, tuple[str, str]] = {}
    for record in records:
        record.company_slug = company_slug_by_identity[record.company_identity]
        record.product_slug = product_slug_by_identity[record.product_identity]
        record.company_id = stable_bigint("company", record.company_slug)
        record.product_id = stable_bigint("product", record.product_slug)
        for namespace, value, key in (
            ("company", record.company_id, record.company_slug),
            ("product", record.product_id, record.product_slug),
        ):
            previous = seen_ids.get(value)
            marker = (namespace, key)
            if previous is not None and previous != marker:
                raise RuntimeError(f"Stable BIGINT collision between {previous!r} and {marker!r}")
            seen_ids[value] = marker


def assign_listings(records: list[PhoneRecord], canonical_source: str) -> None:
    groups: dict[tuple[int, str], list[PhoneRecord]] = {}
    seen_urls: dict[str, PhoneRecord] = {}
    for record in records:
        if record.source_domain == canonical_source:
            continue
        if record.source_url in seen_urls:
            other = seen_urls[record.source_url]
            raise ConversionError(
                "DUPLICATE_URL",
                f"Duplicate listing URL in {other.source_file} and {record.source_file}: {record.source_url}",
            )
        seen_urls[record.source_url] = record
        record.listing_id = stable_bigint("listing", record.source_url)
        groups.setdefault((record.product_id, record.source_domain), []).append(record)

    for group_records in groups.values():
        for index, record in enumerate(sorted(group_records, key=lambda r: (r.source_url, r.source_file)), start=1):
            record.instance_number = index


